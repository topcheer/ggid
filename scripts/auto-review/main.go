func reviewOAuth21(repoRoot string) []Finding {
	var findings []Finding
	p := filepath.Join(repoRoot, "services/oauth/internal/service/oauth_service.go")
	if content, err := os.ReadFile(p); err == nil {
		text := string(content)
		if strings.Contains(text, `"token"`) || strings.Contains(text, `"id_token"`) {
			lines := strings.Split(text, "\n")
			for i, line := range lines {
				if strings.Contains(line, `"token"`) || strings.Contains(line, `"id_token"`) {
					findings = append(findings, Finding{
						ID: "rfc-oauth21-1", Perspective: "RFC Standards Compliance",
						Category: "OAuth 2.1", Severity: "High",
						File: "services/oauth/internal/service/oauth_service.go", Line: i + 1,
						Title: "Implicit/hybrid flow response types may violate OAuth 2.1",
						Description: "OAuth 2.1 disallows the implicit flow (response_type=token). If 'token' or 'id_token' response types are advertised or accepted, clients may attempt flows that are insecure by design.",
						Evidence: strings.TrimSpace(line),
						Recommendation: "Remove 'token' and 'id_token' from ResponseTypesSupported. Only advertise 'code'.",
					})
					break
				}
			}
		}
		if strings.Contains(text, `"password"`) && strings.Contains(text, "GrantTypesSupported") {
			findings = append(findings, Finding{
				ID: "rfc-oauth21-2", Perspective: "RFC Standards Compliance",
				Category: "OAuth 2.1", Severity: "Medium",
				File: "services/oauth/internal/service/oauth_service.go", Line: 0,
				Title: "Password grant type advertised in discovery",
				Description: "OAuth 2.1 removes the password grant type (RFC 6749 §4.3). While still present for backward compatibility, advertising it encourages insecure patterns.",
				Evidence: "GrantTypesSupported includes 'password'",
				Recommendation: "Consider deprecating the password grant. If kept for migration, document it as legacy and recommend authorization code + PKCE.",
			})
		}
	}
	return findings
}

