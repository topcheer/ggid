func reviewOIDC(repoRoot string) []Finding {
	var findings []Finding
	p := filepath.Join(repoRoot, "services/oauth/internal/service/oauth_service.go")
	if content, err := os.ReadFile(p); err == nil {
		text := string(content)
		required := []string{"authorization_endpoint", "userinfo_endpoint", "revocation_endpoint",
			"introspection_endpoint", "response_types_supported", "grant_types_supported",
			"token_endpoint_auth_methods_supported", "code_challenge_methods_supported",
			"scopes_supported", "claims_supported", "id_token_signing_alg_values_supported",
			"subject_types_supported"}
		missing := []string{}
		for _, f := range required {
			if !strings.Contains(text, f) {
				missing = append(missing, f)
			}
		}
		if len(missing) > 0 {
			findings = append(findings, Finding{
				ID: "rfc-oidc-1", Perspective: "RFC Standards Compliance",
				Category: "OIDC Discovery (RFC 8414)", Severity: "Medium",
				File: "services/oauth/internal/service/oauth_service.go", Line: 0,
				Title: "OIDC discovery document missing required fields",
				Description: fmt.Sprintf("The OIDC discovery document is missing required fields per OIDC Core §3: %s", strings.Join(missing, ", ")),
				Evidence: fmt.Sprintf("Missing: %s", strings.Join(missing, ", ")),
				Recommendation: "Add all missing fields to the discovery document to ensure OIDC compliance.",
			})
		}
	}
	return findings
}

